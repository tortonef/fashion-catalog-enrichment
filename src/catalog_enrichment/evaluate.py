"""Evaluate the tagger against hand-checked labels and write docs/eval_results.md.

Usage: python -m catalog_enrichment.evaluate
"""

from __future__ import annotations

import csv
import platform
from datetime import date
from pathlib import Path

from .taxonomy import Group

Labels = dict[str, dict[str, set[str]]]  # image file -> attribute -> values


def load_labels(path: Path) -> Labels:
    """Read labels.csv: one row per image, list values separated by '|'."""
    with path.open(encoding="utf-8", newline="") as f:
        return {
            row["image"]: {k: {v.strip() for v in val.split("|") if v.strip()} for k, val in row.items() if k != "image"}
            for row in csv.DictReader(f)
        }  # fmt: skip


def score(preds: Labels, truth: Labels, groups: list[Group]) -> list[dict]:
    """Accuracy for single-label groups; micro precision/recall for multi-label groups."""
    rows = []
    for g in groups:
        images = [i for i in truth if truth[i].get(g.name) and i in preds]
        row = {
            "attribute": g.name,
            "multi": g.multi,
            "experimental": g.experimental,
            "n": len(images),
        }
        if g.multi:
            tp = sum(len(preds[i][g.name] & truth[i][g.name]) for i in images)
            n_pred = sum(len(preds[i][g.name]) for i in images)
            n_true = sum(len(truth[i][g.name]) for i in images)
            row["precision"] = tp / n_pred if n_pred else 0.0
            row["recall"] = tp / n_true if n_true else 0.0
        else:
            hits = sum(preds[i][g.name] == truth[i][g.name] for i in images)
            row["accuracy"] = hits / len(images) if images else 0.0
        rows.append(row)
    return rows


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def render(rows: list[dict], n_images: int, avg_seconds: float, model_id: str) -> str:
    """Markdown report."""
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `python -m catalog_enrichment.evaluate` on {date.today().isoformat()}.",
        f"Model: `{model_id}` (zero-shot, no fine-tuning). Images: {n_images}. "
        f"Average time per image: {avg_seconds:.2f} s on CPU ({platform.processor() or platform.machine()}).",
        "",
        "| Attribute | Type | Images | Accuracy | Precision | Recall |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        kind = ("multi-label" if r["multi"] else "single-label") + (
            " (experimental)" if r["experimental"] else ""
        )
        if r["n"] == 0:
            lines.append(f"| {r['attribute']} | {kind} | 0 | not labelled | - | - |")
        elif r["multi"]:
            lines.append(
                f"| {r['attribute']} | {kind} | {r['n']} | - | {_pct(r['precision'])} | {_pct(r['recall'])} |"
            )
        else:
            lines.append(
                f"| {r['attribute']} | {kind} | {r['n']} | {_pct(r['accuracy'])} | - | - |"
            )
    lines += [
        "",
        "Accuracy: share of images where the predicted value equals the label. "
        "Precision/recall (multi-label, micro-averaged): share of predicted values that are correct / "
        "share of true values that were found.",
        "",
        "Small sample: treat these numbers as indicative, not as a benchmark.",
        "",
    ]  # fmt: skip
    return "\n".join(lines)


def main() -> None:
    from .config import load_config
    from .factory import build_tagger
    from .tagger import list_images

    cfg = load_config()
    truth = load_labels(cfg["paths"]["labels"])
    tagger = build_tagger(cfg)
    paths = [p for p in list_images(cfg["paths"]["images"]) if p.name in truth]
    if not paths:
        raise SystemExit("No labelled images found: check data/eval/labels.csv and data/images/.")
    items = tagger.tag_paths(paths)
    preds = {it.image: {k: set(a.values) for k, a in it.attributes.items()} for it in items}
    rows = score(preds, truth, tagger.groups)
    report = render(
        rows, len(items), sum(i.seconds for i in items) / len(items), cfg["model"]["id"]
    )
    out = cfg["paths"]["eval_report"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(report)
    print(f"Written to {out}")


if __name__ == "__main__":
    main()
